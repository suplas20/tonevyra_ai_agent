param(
    [switch]$BootstrapDatabase,
    [switch]$InstallLightroomPlugin
)

. (Join-Path $PSScriptRoot "Common.ps1")

$root = Get-TonevyraRoot
$examplePath = Join-Path $root ".env.example"
$envPath = Join-Path $root ".env"

if (-not (Test-Path -LiteralPath $envPath)) {
    if (-not (Test-Path -LiteralPath $examplePath)) {
        throw "Configuration template is missing: $examplePath"
    }
    $bytes = New-Object byte[] 32
    [Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
    $plannerKey = [BitConverter]::ToString($bytes).Replace("-", "").ToLowerInvariant()
    $content = (Get-Content -LiteralPath $examplePath -Raw -Encoding UTF8).Replace(
        "CHANGE_ME_PLANNER_API_KEY",
        $plannerKey
    )
    Set-Content -LiteralPath $envPath -Value $content -Encoding UTF8
    Write-Host "[OK] Created .env and generated a Planner API key."
    Write-Warning "Replace CHANGE_ME_DATABASE_PASSWORD in .env with the tonevyra_app PostgreSQL password."
} else {
    Write-Host "[OK] Preserved the existing .env."
}

Import-TonevyraEnv -Root $root -Require
Set-TonevyraDerivedEnv -Root $root

$runtimeDirectories = @(
    "runtime\input",
    "runtime\output\temp",
    "runtime\output\pass",
    "runtime\output\review_required",
    "runtime\output\failed",
    "runtime\artifacts",
    "runtime\previews",
    "runtime\planner_server",
    "runtime\bridge\requests",
    "runtime\bridge\processing",
    "runtime\bridge\responses",
    "runtime\bridge\errors",
    "runtime\bridge\lightroom_apply_requests",
    "runtime\bridge\lightroom_apply_processing",
    "runtime\bridge\lightroom_apply_processed",
    "runtime\bridge\lightroom_apply_results",
    "runtime\bridge\lightroom_apply_errors",
    "runtime\bridge\lightroom_export_requests",
    "runtime\bridge\lightroom_export_processing",
    "runtime\bridge\lightroom_export_processed",
    "runtime\bridge\lightroom_export_results",
    "runtime\bridge\lightroom_export_errors",
    "runtime\bridge\lightroom_mask_requests",
    "runtime\bridge\lightroom_mask_processing",
    "runtime\bridge\lightroom_mask_processed",
    "runtime\bridge\lightroom_mask_results",
    "runtime\bridge\lightroom_mask_errors",
    "logs"
)
foreach ($relativePath in $runtimeDirectories) {
    New-Item -ItemType Directory -Force -Path (Join-Path $root $relativePath) | Out-Null
}
Write-Host "[OK] Runtime directories are ready."

$modelIndex = Join-Path $root "models\qwen3-vl-4b-instruct\model.safetensors.index.json"
if (-not (Test-Path -LiteralPath $modelIndex -PathType Leaf)) {
    throw "Qwen model index is missing: $modelIndex"
}
Write-Host "[OK] Local Qwen model found."

if ($InstallLightroomPlugin) {
    $sourcePlugin = Join-Path $root "lightroom\TonevyraAI.lrplugin"
    $bridgeRoot = (Join-Path $root "runtime\bridge").Replace("\", "\\")
    $bridgeConfig = @"
-- Generated by Tonevyra portable initialization.
return {
  root = [[$bridgeRoot]],
}
"@
    Set-Content -LiteralPath (Join-Path $sourcePlugin "BridgeConfig.lua") -Value $bridgeConfig -Encoding UTF8
    $modulesRoot = Join-Path $env:APPDATA "Adobe\Lightroom\Modules"
    $targetPlugin = Join-Path $modulesRoot "TonevyraAI.lrplugin"
    New-Item -ItemType Directory -Force -Path $modulesRoot | Out-Null
    Copy-Item -LiteralPath $sourcePlugin -Destination $targetPlugin -Recurse -Force
    Write-Host "[OK] Lightroom Plugin installed: $targetPlugin"
}

if ($BootstrapDatabase) {
    if ((Get-Content -LiteralPath $envPath -Raw) -match "CHANGE_ME_DATABASE_PASSWORD") {
        throw "Replace CHANGE_ME_DATABASE_PASSWORD in .env first."
    }
    $agentExe = Join-Path $root "Agent\TonevyraAI.exe"
    $process = Start-Process -FilePath $agentExe `
        -ArgumentList @("installer-db", "bootstrap-schema") `
        -WorkingDirectory $root `
        -Wait `
        -PassThru
    if ($process.ExitCode -ne 0) {
        throw "PostgreSQL schema bootstrap failed (exit=$($process.ExitCode)). Check the DB, role, and .env."
    }
    Write-Host "[OK] PostgreSQL baseline schema is ready."
}

Write-Host ""
Write-Host "Next steps:"
Write-Host "1. Verify the PostgreSQL password in .env"
Write-Host "2. scripts\Check-Prerequisites.ps1"
Write-Host "3. scripts\Start-PlannerServer.ps1"
Write-Host "4. scripts\Start-Agent.ps1"
